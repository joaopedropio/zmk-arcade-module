static int glyph_of(char c) {
    if (c >= '0' && c <= '9') {
        return 1 + (c - '0');
    }
    if (c >= 'A' && c <= 'Z') {
        return 11 + (c - 'A');
    }
    return 0;
}

int pm_text_w(const char *s, int scale) {
    int n = (int)strlen(s);
    return n == 0 ? 0 : (n * PM_GLYPH_ADV - 1) * scale;
}

void pm_text(int x, int y, int scale, uint16_t c, const char *s) {
    for (; *s != '\0'; s++, x += PM_GLYPH_ADV * scale) {
        const uint8_t *g = FONT[glyph_of(*s)];
        for (int i = 0; i < PM_GLYPH_W; i++) {
            for (int j = 0; j < PM_GLYPH_H; j++) {
                if (g[i] & (1u << j)) {
                    pm_fill(x + i * scale, y + j * scale, scale, scale, c);
                }
            }
        }
    }
}

void pm_digits(uint32_t value, int digits, char *buf) {
    for (int i = digits - 1; i >= 0; i--) {
        buf[i] = (char)('0' + value % 10);
        value /= 10;
    }
    buf[digits] = '\0';
}
